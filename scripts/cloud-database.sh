#!/usr/bin/env bash
set -euo pipefail
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"
source scripts/cloud-env.sh
# Validate an existing config before creating roles or databases.
node --input-type=module <<'JS'
import { existsSync, readFileSync } from 'node:fs';
if (existsSync('.runtime/local.json')) {
  const c = JSON.parse(readFileSync('.runtime/local.json', 'utf8'));
  if (c.LUMIRA_DB_URL !== 'jdbc:postgresql://127.0.0.1:5432/lumira_next' || c.LUMIRA_DB_USER !== 'lumira_next')
    throw new Error('Cloud startup requires the isolated local lumira_next development database.');
}
JS
if [[ ${LUMIRA_CLOUD_PG_MODE:-system} == user ]]; then
  exec bash scripts/cloud-database-user.sh
fi
as_root() { if [[ $EUID == 0 ]]; then "$@"; else sudo -n "$@"; fi; }
if ! pg_lsclusters --no-header | awk '$1 == "18" && $2 == "main" {found=1} END {exit !found}'; then
  as_root pg_createcluster 18 main --port 5432
fi
cluster_port=$(pg_lsclusters --no-header | awk '$1 == "18" && $2 == "main" {print $3}')
[[ $cluster_port == 5432 ]] || { echo 'PostgreSQL 18 main must use port 5432 in this VM.' >&2; exit 1; }
if ! pg_lsclusters --no-header | awk '$1 == "18" && $2 == "main" && $4 ~ /^online/ {found=1} END {exit !found}'; then
  as_root pg_ctlcluster 18 main start
fi
"$PSQL_BIN" --version
for attempt in {1..30}; do
  /usr/lib/postgresql/18/bin/pg_isready -h 127.0.0.1 -p 5432 && break
  sleep 1
done
/usr/lib/postgresql/18/bin/pg_isready -h 127.0.0.1 -p 5432
# Linux uses peer authentication for the postgres administrator. The application
# still connects over TCP with its own random password generated by init-local.
cat > .runtime/cloud-psql-admin.sh <<'SH'
#!/usr/bin/env bash
set -euo pipefail
if [[ $EUID == 0 ]]; then
  exec runuser -u postgres -- env PGHOST=/var/run/postgresql PGPORT=5432 PGUSER=postgres PGPASSWORD= /usr/lib/postgresql/18/bin/psql "$@"
fi
exec sudo -n -u postgres env PGHOST=/var/run/postgresql PGPORT=5432 PGUSER=postgres PGPASSWORD= /usr/lib/postgresql/18/bin/psql "$@"
SH
chmod 700 .runtime/cloud-psql-admin.sh
PSQL_BIN="$root/.runtime/cloud-psql-admin.sh" node scripts/init-local.mjs
